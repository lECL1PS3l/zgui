/// Расшифровка кода для отчёта.
pub fn explain(code: &str) -> Option<&'static str> {
    ALL.iter().find(|(c, _)| *c == code).map(|(_, e)| *e)
}

/// Находит все коды вида `[E-XXX-000]` в тексте журнала (без дублей, по порядку).
pub fn codes_in(text: &str) -> Vec<&str> {
    let bytes = text.as_bytes();
    let mut out: Vec<&str> = Vec::new();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'[' {
            if let Some(close) = text[i + 1..].find(']') {
                let candidate = &text[i + 1..i + 1 + close];
                if is_code(candidate) && !out.contains(&candidate) {
                    out.push(candidate);
                }
                i += 1 + close;
            }
        }
        i += 1;
    }
    out
}

/// `E-XXX-000` / `W-XXX-000`: префикс, 2-5 заглавные буквы группы, 3 цифры.
fn is_code(s: &str) -> bool {
    let mut parts = s.split('-');
    let (Some(prefix), Some(group), Some(num), None) =
        (parts.next(), parts.next(), parts.next(), parts.next())
    else {
        return false;
    };
    if prefix != "E" && prefix != "W" {
        return false;
    }
    if !(2..=5).contains(&group.len()) || !group.bytes().all(|b| b.is_ascii_uppercase()) {
        return false;
    }
    num.len() == 3 && num.bytes().all(|b| b.is_ascii_digit())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_ids_are_unique_and_wellformed() {
        let mut seen = std::collections::HashSet::new();
        for (code, text) in ALL {
            assert!(is_code(code), "плохой формат кода: {code}");
            assert!(seen.insert(*code), "дубль кода: {code}");
            assert!(!text.trim().is_empty(), "пустая расшифровка: {code}");
        }
    }

    #[test]
    fn codes_in_finds_dedups_and_ignores_noise() {
        let text = "[2026-01-01] err: не удалось [E-SVC-003] и снова [E-SVC-003], [W-TEST-009], [не код], [E-TOOLONG-001], [E-SVC-01]";
        assert_eq!(codes_in(text), vec!["E-SVC-003", "W-TEST-009"]);
        assert!(explain("E-SVC-003").is_some());
        assert!(explain("E-NONEXIST-000").is_none());
    }
}
